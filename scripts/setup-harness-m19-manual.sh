# Harness M19 TUI Manual Workspace

Generated by `scripts/setup-harness-m19-manual.sh`.

```bash
source harness-m19-test/env.sh
cargo build -p agentpm-cli
(cd "$M19_WORK" && "$APM" harness)
```

Useful quick checks:

```bash
(cd "$M19_WORK" && "$APM" harness --json)
TERM=dumb "$APM" harness --config "$M19_WORK/agentpm.harness.json"
```

The generated directory is ignored by git and can be deleted/regenerated at any time.
MD

cat >"$WORK/context.md" <<'MD'
