mkdir -p "$WORK"

cat >"$ROOT/harness-m19-test/env.sh" <<SH
export M19_ROOT="$ROOT/harness-m19-test"
export M19_WORK="$WORK"
export APM="$ROOT/target/debug/agentpm"
SH

