pkg_root_at() {
  local workspace="$1"
  local kind="$2"
  local owner="$3"
  local name="$4"
  local version="$5"
  printf '%s/.agentpm/%s/%s/%s/%s' "$workspace" "$kind" "$owner" "$name" "$version"
}

pkg_root() {
  pkg_root_at "$WORK" "$@"
}

write_json() {
  local path="$1"
  mkdir -p "$(dirname "$path")"
  cat >"$path"
}

