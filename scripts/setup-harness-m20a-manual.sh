#!/usr/bin/env python3
import json
import sys
from pathlib import Path

if len(sys.argv) != 4:
    raise SystemExit("usage: m20a_assert_capture.py BODIES_JSONL PROVIDER SCENARIO")

path = Path(sys.argv[1])
provider = sys.argv[2]
scenario = sys.argv[3]
rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
if not rows:
    raise SystemExit("capture server recorded no provider bodies")
bodies = [row["body"] for row in rows]
first = bodies[0]

if provider == "openai":
    if first.get("tool_choice") != "required":
        raise SystemExit(f"expected OpenAI tool_choice=required, got {first.get('tool_choice')!r}")
    tools = [((tool.get("function") or {}).get("name"), tool) for tool in first.get("tools") or []]
else:
    if first.get("tool_choice") != {"type": "any"}:
        raise SystemExit(f"expected Anthropic tool_choice={{'type':'any'}}, got {first.get('tool_choice')!r}")
    tools = [(tool.get("name"), tool) for tool in first.get("tools") or []]

phase_tools = [tool for name, tool in tools if name == "phase_complete"]
if not phase_tools:
    raise SystemExit("phase_complete tool was not advertised")
tool_text = json.dumps(phase_tools[0])
if "include" not in tool_text.lower() or "output" not in tool_text.lower():
    raise SystemExit("phase_complete schema/description does not mention including output")

print(f"ok: {provider} {scenario} required tool choice and phase_complete output guidance present")
print(f"captured bodies: {path}")
