#!/usr/bin/env python3
import argparse
import json
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--host", default="127.0.0.1")
parser.add_argument("--port", type=int, required=True)
parser.add_argument("--log", required=True)
parser.add_argument("--provider", choices=["openai", "anthropic"], required=True)
parser.add_argument("--scenario", choices=["fallback", "budget"], required=True)
args = parser.parse_args()

log_path = Path(args.log)
log_path.parent.mkdir(parents=True, exist_ok=True)
sequence = 0

def write_log(path, body):
    global sequence
    sequence += 1
    with log_path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps({
            "sequence": sequence,
            "provider": args.provider,
            "scenario": args.scenario,
            "path": path,
            "body": body,
        }, sort_keys=True) + "\n")

def alias_for(body, prefix):
    for tool in body.get("tools") or []:
        name = ((tool.get("function") or {}).get("name") or "") if args.provider == "openai" else tool.get("name") or ""
        if name.startswith(prefix):
            return name
    raise RuntimeError(f"missing tool alias starting with {prefix}")

def phase_complete_outcomes(body):
    for tool in body.get("tools") or []:
        if args.provider == "openai":
            function = tool.get("function") or {}
            if function.get("name") != "phase_complete":
                continue
            schema = function.get("parameters") or {}
        else:
            if tool.get("name") != "phase_complete":
                continue
            schema = tool.get("input_schema") or {}
        outcome = ((schema.get("properties") or {}).get("outcome") or {})
        enum = outcome.get("enum") or []
        return [str(value) for value in enum]
    return []

def openai_tool_response(alias, call_id, arguments, text=None):
    return {
        "id": "chatcmpl-m20a-capture",
        "object": "chat.completion",
        "choices": [{
            "index": 0,
            "message": {
                "role": "assistant",
                "content": text,
                "tool_calls": [{
                    "id": call_id,
                    "type": "function",
                    "function": {"name": alias, "arguments": json.dumps(arguments)},
                }],
            },
            "finish_reason": "tool_calls",
        }],
        "usage": {"prompt_tokens": 1, "completion_tokens": 1, "total_tokens": 2},
    }

def anthropic_tool_response(alias, call_id, arguments, text=None):
    content = []
    if text:
        content.append({"type": "text", "text": text})
    content.append({"type": "tool_use", "id": call_id, "name": alias, "input": arguments})
    return {
        "id": "msg_m20a_capture",
        "type": "message",
        "role": "assistant",
        "content": content,
        "stop_reason": "tool_use",
        "usage": {"input_tokens": 1, "output_tokens": 1},
    }

def tool_response(body, prefix, call_id, arguments, text=None):
    alias = alias_for(body, prefix)
    if args.provider == "openai":
        return openai_tool_response(alias, call_id, arguments, text)
    return anthropic_tool_response(alias, call_id, arguments, text)

def long_output(n):
    sentence = (
        f"M20A budget output step {n}: this intentionally verbose phase answer "
        "describes status, evidence, consequence, recommendation, and residual risk. "
    )
    return {"summary": sentence * 70}

def response_for(body):
    if args.scenario == "fallback":
        outcomes = phase_complete_outcomes(body)
        if "respond" in outcomes and "done" not in outcomes:
            return tool_response(
                body,
                "phase_complete",
                f"call_m20a_fallback_{sequence}",
                {"outcome": "respond"},
                "M20A fallback answer from completing assistant content.",
            )
        return tool_response(
            body,
            "phase_complete",
            f"call_m20a_done_{sequence}",
            {
                "outcome": "done",
                "output": {"summary": "M20A terminal output survived from canonical phase output."},
            },
        )
    if args.scenario == "budget":
        outcome = "done" if sequence >= 6 else "next"
        return tool_response(
            body,
            "phase_complete",
            f"call_m20a_budget_{sequence}",
            {"outcome": outcome, "output": long_output(sequence)},
        )
    raise RuntimeError("unknown scenario")

class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        if self.path == "/health":
            self.send_response(200)
            self.end_headers()
            self.wfile.write(b"ok")
            return
        self.send_response(404)
        self.end_headers()

    def do_POST(self):
        length = int(self.headers.get("content-length", "0"))
        body = json.loads(self.rfile.read(length) or b"{}")
        write_log(self.path, body)
        try:
            response = response_for(body)
            payload = json.dumps(response).encode()
            self.send_response(200)
        except Exception as exc:
            payload = json.dumps({"error": str(exc)}).encode()
            self.send_response(500)
        self.send_header("content-type", "application/json")
        self.send_header("content-length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def log_message(self, fmt, *values):
        return

ThreadingHTTPServer((args.host, args.port), Handler).serve_forever()
