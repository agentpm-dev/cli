#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

def stable_json(value: Any) -> str:
    return json.dumps(value if value is not None else {}, sort_keys=True, separators=(",", ":"))

def load_events(path: Path) -> list[dict[str, Any]]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]

RUNTIME_FIELD_KEYS = {
    "attempt",
    "error",
    "provider_alias",
    "provider_call_id",
    "result",
    "source",
}

def model_argument_fields(event: dict[str, Any]) -> dict[str, Any]:
    fields = (event.get("payload") or {}).get("fields") or {}
    if isinstance(fields.get("arguments"), dict):
        return fields["arguments"]
    return {
        key: value
        for key, value in fields.items()
        if key not in RUNTIME_FIELD_KEYS
    }

def action_key(event: dict[str, Any]) -> tuple[str, str, str] | None:
    payload = event.get("payload") or {}
    if payload.get("payload_type") != "action":
        return None
    kind = payload.get("action_kind")
    identity = payload.get("identity")
    if not kind or not identity or kind == "phase_completion":
        return None
    return str(kind), str(identity), stable_json(model_argument_fields(event))

def action_identity_key(event: dict[str, Any]) -> tuple[str, str] | None:
    payload = event.get("payload") or {}
    if payload.get("payload_type") != "action":
        return None
    kind = payload.get("action_kind")
    identity = payload.get("identity")
    if not kind or not identity or kind == "phase_completion":
        return None
    return str(kind), str(identity)

def proposed_phase_completions(fields: dict[str, Any]) -> list[dict[str, Any]]:
    return [
        action
        for action in fields.get("proposed_actions") or []
        if action.get("action_kind") == "phase_completion"
    ]

COMPLETED_EVENTS = {
    "knowledge_retrieved",
    "mcp_tool_completed",
    "memory_read_completed",
    "memory_write_completed",
    "semantic_action_completed",
    "skill_resource_loaded",
    "tool_completed",
}

FAILED_EVENTS = {
    "knowledge_failed",
    "mcp_tool_failed",
    "memory_read_failed",
    "memory_write_failed",
    "semantic_action_failed",
    "skill_resource_failed",
    "tool_failed",
}

def summarize(events: list[dict[str, Any]]) -> dict[str, Any]:
    by_phase: dict[str, Counter[tuple[str, str, str]]] = defaultdict(Counter)
    seen_phase_for_action: dict[tuple[str, str, str], set[str]] = defaultdict(set)
    by_phase_identity: dict[str, dict[tuple[str, str], Counter[str]]] = defaultdict(lambda: defaultdict(Counter))
    seen_phase_for_identity: dict[tuple[str, str], dict[str, Counter[str]]] = defaultdict(lambda: defaultdict(Counter))
    action_status_by_phase: dict[str, dict[tuple[str, str, str], str]] = defaultdict(dict)
    prior_status_by_action: dict[tuple[str, str, str], list[str]] = defaultdict(list)
    repairs = Counter()
    fallback = Counter()
    budget_headers = Counter()
    outcome_distribution = Counter()
    successful_cross_repeats = 0
    failed_cross_repeats = 0
    counters = Counter()

    for event in events:
        event_type = event.get("event_type")
        payload = event.get("payload") or {}
        fields = payload.get("fields") or {}
        phase_id = event.get("phase_execution_id") or "no-phase"

        if event_type == "semantic_action_proposed":
            key = action_key(event)
            if key:
                by_phase[str(phase_id)][key] += 1
                prior_statuses = prior_status_by_action.get(key, [])
                if "completed" in prior_statuses:
                    successful_cross_repeats += 1
                elif "failed" in prior_statuses:
                    failed_cross_repeats += 1
                seen_phase_for_action[key].add(str(phase_id))
            identity_key = action_identity_key(event)
            if identity_key:
                fields_key = stable_json(model_argument_fields(event))
                by_phase_identity[str(phase_id)][identity_key][fields_key] += 1
                seen_phase_for_identity[identity_key][str(phase_id)][fields_key] += 1
        elif event_type in COMPLETED_EVENTS | FAILED_EVENTS:
            key = action_key(event)
            if key:
                action_status_by_phase[str(phase_id)][key] = (
                    "completed" if event_type in COMPLETED_EVENTS else "failed"
                )
        elif event_type == "phase_result_ready":
            phase_payload_id = payload.get("phase_id") or "unknown"
            outcome = payload.get("outcome") or "unknown"
            outcome_distribution[f"{phase_payload_id}:{outcome}"] += 1
            for key, status in action_status_by_phase.pop(str(phase_id), {}).items():
                prior_status_by_action[key].append(status)
            if payload.get("output") is None:
                counters["phase_result_null_outputs"] += 1
            else:
                counters["phase_result_outputs"] += 1
        elif event_type == "run_completed":
            if payload.get("output") is None:
                counters["run_completed_null_outputs"] += 1
            else:
                counters["run_completed_outputs"] += 1
        elif event_type == "model_repair_requested":
            counters["model_repair_requested"] += 1
            repairs[str(fields.get("repair_kind") or "unknown")] += 1
        elif event_type == "phase_output_fallback":
            fallback[f"{payload.get('status')}:{payload.get('source')}"] += 1
        elif event_type == "model_request_completed":
            completions = proposed_phase_completions(fields)
            if completions:
                counters["completing_turns"] += len(completions)
                if fields.get("assistant_content"):
                    counters["completing_turns_with_assistant_content"] += len(completions)
                for action in completions:
                    action_fields = action.get("fields") or {}
                    if action_fields.get("output") is None:
                        counters["phase_completion_without_output"] += 1
                    else:
                        counters["phase_completion_with_output"] += 1
        elif event_type == "prompt_prepared":
            prompt = fields.get("prompt") or ""
            if "[cross-phase detail budget:" in prompt:
                counters["section4_budget_prompts"] += 1
                for header in re.findall(r"\[cross-phase detail budget:[^\]]+\]", prompt):
                    budget_headers[header] += 1
            if "[cross-phase output detail marker:" in prompt:
                counters["section4_budget_marker_prompts"] += 1
            counters["section4_output_stub_markers"] += prompt.count("output: [omitted:")

    within_repeats = 0
    for counter in by_phase.values():
        within_repeats += sum(count - 1 for count in counter.values() if count > 1)
    cross_repeats = 0
    for phases in seen_phase_for_action.values():
        if len(phases) > 1:
            cross_repeats += len(phases) - 1
    within_same_action_rework = 0
    within_changed_argument_rework = 0
    for actions in by_phase_identity.values():
        for fields_counter in actions.values():
            total = sum(fields_counter.values())
            if total > 1:
                within_same_action_rework += total - 1
            if len(fields_counter) > 1:
                within_changed_argument_rework += total - max(fields_counter.values())
    cross_same_action_rework = 0
    cross_changed_argument_rework = 0
    for phases in seen_phase_for_identity.values():
        if len(phases) > 1:
            cross_same_action_rework += len(phases) - 1
            all_fields = set()
            for fields_counter in phases.values():
                all_fields.update(fields_counter)
            if len(all_fields) > 1:
                cross_changed_argument_rework += len(phases) - 1

    return {
        "events": len(events),
        "within_phase_exact_repeats": within_repeats,
        "cross_phase_exact_repeats": cross_repeats,
        "within_phase_same_action_rework": within_same_action_rework,
        "within_phase_changed_argument_rework": within_changed_argument_rework,
        "cross_phase_same_action_rework": cross_same_action_rework,
        "cross_phase_changed_argument_rework": cross_changed_argument_rework,
        "cross_phase_repeats_after_success": successful_cross_repeats,
        "cross_phase_repeats_after_failure": failed_cross_repeats,
        **dict(counters),
        "outcome_distribution": dict(sorted(outcome_distribution.items())),
        "section4_budget_headers": dict(budget_headers),
        "repairs_by_kind": dict(repairs),
        "phase_output_fallback": dict(fallback),
    }

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("events_jsonl", type=Path)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    summary = summarize(load_events(args.events_jsonl))
    if args.json:
        print(json.dumps(summary, indent=2, sort_keys=True))
        return
    for key in sorted(summary):
        value = summary[key]
        if isinstance(value, dict):
            print(f"{key}: {json.dumps(value, sort_keys=True)}")
        else:
            print(f"{key}: {value}")

if __name__ == "__main__":
    main()
